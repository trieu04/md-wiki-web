import { execFileSync } from 'node:child_process';
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileFromFile } from 'json-schema-to-typescript';

const root = fileURLToPath(new URL('../../../', import.meta.url));
const contracts = join(root, 'packages/contracts');
const worker = join(root, 'services/worker');
const modelsDir = 'src/mdwiki_worker/contracts';
const mode = process.argv[2];
if (mode !== 'gen' && mode !== 'check') throw new Error('Expected gen or check');

const temp = mkdtempSync(join(tmpdir(), 'mdwiki-contracts-'));
const schemaDir = join(contracts, 'jobs');
const tsJobs = 'src/jobs';
const run = (cmd, args, opts) => execFileSync(cmd, args, { cwd: root, stdio: 'inherit', ...opts });
const names = (dir, suffix) =>
  existsSync(dir)
    ? readdirSync(dir)
        .filter((name) => name.endsWith(suffix))
        .sort()
    : [];

try {
  const openapi = join(temp, 'openapi.json');
  const declaration = join(temp, 'src/schema.d.ts');
  mkdirSync(join(temp, tsJobs), { recursive: true });
  run('pnpm', ['--filter', '@md-wiki/domain', 'build']);
  run('pnpm', ['--filter', '@md-wiki/api', 'exec', 'tsx', 'scripts/openapi.ts', openapi], {
    env: { ...process.env, NODE_ENV: 'development' },
  });
  run('pnpm', [
    '--filter',
    '@md-wiki/contracts',
    'exec',
    'openapi-typescript',
    openapi,
    '--alphabetize',
    '-o',
    declaration,
  ]);

  for (const name of names(schemaDir, '.schema.json')) {
    const output = join(temp, tsJobs, name.replace(/\.schema\.json$/, '.ts'));
    const content = await compileFromFile(join(schemaDir, name), {
      bannerComment: '/* Generated by pnpm contracts:gen. Do not edit. */',
    });
    writeFileSync(output, content);
  }
  run(
    'uv',
    [
      'run',
      '--locked',
      'datamodel-codegen',
      '--input',
      schemaDir,
      '--input-file-type',
      'jsonschema',
      '--output',
      `${join(temp, modelsDir)}/`,
      '--output-model-type',
      'pydantic_v2.BaseModel',
      '--target-python-version',
      '3.12',
      '--disable-timestamp',
      '--use-title-as-name',
      '--snake-case-field',
      '--field-constraints',
      '--strict-types',
      'str',
      'int',
      '--formatters',
      'ruff-check',
      'ruff-format',
    ],
    { cwd: worker },
  );

  const changes = [];
  function sync(relative, destination) {
    const generated = join(temp, relative);
    const target = join(destination, relative);
    if (mode === 'gen') {
      if (existsSync(generated)) {
        mkdirSync(dirname(target), { recursive: true });
        copyFileSync(generated, target);
      } else {
        rmSync(target);
      }
    } else if (
      !existsSync(generated) ||
      !existsSync(target) ||
      !readFileSync(generated).equals(readFileSync(target))
    ) {
      changes.push(target.slice(root.length));
    }
  }
  function syncDir(relative, destination, suffix) {
    const files = new Set([
      ...names(join(temp, relative), suffix),
      ...names(join(destination, relative), suffix),
    ]);
    for (const file of files) sync(join(relative, file), destination);
  }
  sync('openapi.json', contracts);
  sync('src/schema.d.ts', contracts);
  syncDir(tsJobs, contracts, '.ts');
  syncDir(modelsDir, worker, '.py');
  if (changes.length) {
    console.error(
      `Generated contracts are out of date:\n${changes.join('\n')}\nRun pnpm contracts:gen.`,
    );
    process.exitCode = 1;
  }
} finally {
  rmSync(temp, { force: true, recursive: true });
}
